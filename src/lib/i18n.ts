export type LanguageCode = import('./config').UserLanguage

export const i18n: Record<LanguageCode, typeof en> = {
  en,
  zh,
  fr,
  de,
  es,
  ar,
  hi,
  ru,
  pt,
}

export const getTranslation = (lang: LanguageCode) => {
  return i18n[lang] || i18n.en
}

const LANGUAGE_CODE_ALIASES: Record<string, string> = {
  english: 'en',
  chinese: 'zh',
  'simplified chinese': 'zh-Hans',
  'traditional chinese': 'zh-Hant',
  'zh-hans': 'zh-Hans',
  'zh-hant': 'zh-Hant',
  french: 'fr',
  german: 'de',
  japanese: 'ja',
  korean: 'ko',
  russian: 'ru',
  spanish: 'es',
  portuguese: 'pt',
  italian: 'it',
  arabic: 'ar',
  hindi: 'hi',
}

export const getLanguageName = (langCode: string, interfaceLang: LanguageCode): string => {
  const normalized = String(langCode || '')
    .toLowerCase()
    .trim()
    .replace(/[\[\]()]/g, '')
  const code = LANGUAGE_CODE_ALIASES[normalized] || normalized

  try {
    const name = new Intl.DisplayNames([interfaceLang], { type: 'language' }).of(code)
    if (name && name.toLowerCase() !== code.toLowerCase()) return name
  } catch {
    // Keep the original token when the runtime cannot name this language.
  }

  return langCode
}
